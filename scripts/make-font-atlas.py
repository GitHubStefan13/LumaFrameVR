#!/usr/bin/env python3
"""Bake Inter into the bitmap atlases the software canvas draws with.

The interface renders into a software canvas and has no font engine, and the project takes no
new dependencies, so the typeface is baked here into tight bitmaps and generated C++ headers.
Inter is licensed under the SIL Open Font License 1.1 (see licenses/Inter-OFL.txt), which
permits this; the licence travels with the payload.

Regenerate with:

    python3 scripts/make-font-atlas.py --fonts /path/to/inter/4.0

The fonts are Inter 4.0 (static weights), from https://github.com/rsms/inter.

Sizes follow the interface typography: a dialog title is SemiBold at 24, file names Regular at
17, buttons and sidebar rows Medium at 16 to 17, secondary text Regular at 14. VR panels are
viewed at a distance, so these are scaled up a little here, which the same reference asks for.
"""
import argparse
import subprocess
import sys
from pathlib import Path

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:  # pragma: no cover
    raise SystemExit('make-font-atlas.py: Pillow is needed to bake the atlases')

# role, file, pixel size, and the interface size it stands for
STYLES = (
    ('title', 'Inter-SemiBold.otf', 26, 'dialog title, 24 at 600'),
    ('body', 'Inter-Regular.otf', 20, 'file names, 17 at 400'),
    ('medium', 'Inter-Medium.otf', 19, 'buttons, sidebar rows and breadcrumbs, 16 to 17 at 500'),
    ('secondary', 'Inter-Regular.otf', 15, 'secondary text, 14 at 400'),
)
ASCII_FIRST, ASCII_LAST = 0x20, 0x7E

# Characters beyond ASCII that the interface actually uses: the accented letters in the
# translation files, the symbols those files use, and the marks the player draws.
EXTRAS = (0x00AB, 0x00B0, 0x00B7, 0x00BB, 0x00C9, 0x00CC, 0x00CD, 0x00D7, 0x00E0, 0x00E1,
          0x00E7, 0x00E8, 0x00E9, 0x00EA, 0x00ED, 0x00F1, 0x00F3, 0x00F4, 0x00FA, 0x0152,
          0x2014, 0x2026, 0x2039, 0x203A, 0x2192, 0x25B6, 0x25A0, 0x2022)
# Latin-1 plus the common Latin Extended-A letters, so another European language does not need a
# re-bake: German umlauts, the Nordic and Polish and Czech letters, and their capitals.
EXTRAS = tuple(sorted(set(EXTRAS) | set(range(0x00C0, 0x0100)) | {
    0x0110, 0x0111, 0x0139, 0x013D, 0x013E, 0x0141, 0x0142, 0x0143, 0x0144, 0x0150, 0x0151,
    0x0152, 0x0153, 0x0158, 0x0159, 0x015A, 0x015B, 0x015E, 0x015F, 0x0160, 0x0161, 0x0164,
    0x0165, 0x016E, 0x016F, 0x0170, 0x0171, 0x0178, 0x0179, 0x017A, 0x017D, 0x017E, 0x20AC}))


def characters():
    return [chr(code) for code in range(ASCII_FIRST, ASCII_LAST + 1)] + [chr(code) for code in EXTRAS]


def bake(style, font_path, size):
    """One glyph per character, cropped to its ink, with the metrics the renderer needs."""
    font = ImageFont.truetype(str(font_path), size)  # noqa: E501 the metrics below are the bake's contract
    ascent, descent = font.getmetrics()
    pixels = bytearray()
    glyphs = []
    for character in characters():
        left, top, right, bottom = font.getbbox(character)
        width, height = int(max(0, right - left)), int(max(0, bottom - top))
        advance = round(font.getlength(character))
        offset = len(pixels)
        if width and height:
            mask = Image.new('L', (width, height), 0)
            ImageDraw.Draw(mask).text((-left, -top), character, font=font, fill=255)
            pixels.extend(mask.tobytes())
        glyphs.append((offset, advance, width, height, left, top))
    line_height = ascent + descent
    return pixels, glyphs, ascent, line_height


def header(style, size, pixels, glyphs, ascent, line_height, source):
    out = ['#pragma once', '#include <array>', '#include <cstdint>',
           '#include "font_atlas.hpp"', '',
           '// Generated by scripts/make-font-atlas.py from %s, %s. Inter is under the SIL Open' % (source, STYLES_BY_NAME[style][3]),
           '// Font License 1.1; see licenses/Inter-OFL.txt. Do not edit by hand.', '',
           'namespace lumaframevr::ui::fonts {', '',
           'inline constexpr int %s_size = %d;' % (style, size),
           'inline constexpr int %s_ascent = %d;' % (style, ascent),
           'inline constexpr int %s_line_height = %d;' % (style, line_height),
           'inline constexpr int %s_first = %d;' % (style, ASCII_FIRST),
           'inline constexpr int %s_last = %d;' % (style, ASCII_LAST), '']
    out.append('inline constexpr std::array<std::uint8_t, %d> %s_pixels{{' % (len(pixels), style))
    for start in range(0, len(pixels), 32):
        out.append('    ' + ','.join(str(value) for value in pixels[start:start + 32]) + ',')
    out.append('}};')
    out.append('')
    out.append('// The codepoints after %s_last, in the order the glyphs follow them.' % style)
    out.append('inline constexpr std::array<char32_t, %d> %s_extras{{%s}};' % (
        len(EXTRAS), style, ','.join('0x%04X' % code for code in EXTRAS)))
    out.append('')
    out.append('inline constexpr std::array<Glyph, %d> %s_glyphs{{' % (len(glyphs), style))
    for offset, advance, width, height, left, top in glyphs:
        out.append('    {%d,%d,%d,%d,%d,%d},' % (offset, advance, width, height, left, top))
    out.append('}};')
    out.append('}')
    out.append('')
    return '\n'.join(out)


def specimen(directory, fonts):
    """A specimen sheet drawn from the same fonts, so the sizes can be judged before any of it
    is wired into the interface."""
    directory.mkdir(parents=True, exist_ok=True)
    width, height = 900, 420
    image = Image.new('RGB', (width, height), (14, 14, 14))
    draw = ImageDraw.Draw(image)
    y = 24
    for style, filename, size, note in STYLES:
        font = ImageFont.truetype(str(fonts / filename), size)
        draw.text((24, y), 'LumaFrameVR', font=font, fill=(237, 237, 237))
        draw.text((520, y + 6), 'Yaw +0.0 deg', font=font, fill=(176, 176, 176))
        caption = ImageFont.truetype(str(fonts / 'Inter-Regular.otf'), 13)
        draw.text((24, y + size + 4), '%s: %s at %d px' % (style, note, size), font=caption, fill=(110, 110, 110))
        y += size + 44
    image.save(directory / 'font-specimen.png')
    return directory / 'font-specimen.png'


STYLES_BY_NAME = {style: entry for style, entry in ((s[0], s) for s in STYLES)}


def main():
    parser = argparse.ArgumentParser(description='Bake the Inter atlases')
    parser.add_argument('--fonts', type=Path, required=True,
                        help='directory holding the Inter 4.0 static weights (see docs/BUILD.md)')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'cpp/ui/assets')
    parser.add_argument('--specimen', type=Path)
    options = parser.parse_args()
    if not (options.fonts / 'Inter-Regular.otf').is_file():
        raise SystemExit('make-font-atlas.py: no Inter-Regular.otf in %s' % options.fonts)
    total = 0
    for style, filename, size, _note in STYLES:
        font_path = options.fonts / filename
        if not font_path.is_file():
            raise SystemExit('make-font-atlas.py: missing %s' % font_path)
        pixels, glyphs, ascent, line_height = bake(style, font_path, size)
        text = header(style, size, pixels, glyphs, ascent, line_height, filename)
        (options.output / ('font_%s.hpp' % style)).write_text(text, encoding='utf-8')
        total += len(pixels)
        print('%-10s %2d px  %5d glyphs  %6d bytes of ink' % (style, size, len(glyphs), len(pixels)))
    print('%-10s %23s %6d bytes, headers written to %s' % ('total', '', total, options.output))
    if options.specimen:
        print('specimen: %s' % specimen(options.specimen, options.fonts))
    return 0


if __name__ == '__main__':
    sys.exit(main())
