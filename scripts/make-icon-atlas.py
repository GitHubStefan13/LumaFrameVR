#!/usr/bin/env python3
"""Bake the Lucide icon set into the coverage bitmaps the canvas draws.

Lucide is licensed ISC (see licenses/Lucide-ISC.txt). The icons are fetched as SVG and
rasterised here at 24x24, the size the canvas glyph drawing expects, so no rasteriser and no
SVG parser is needed at build or run time.

    python3 scripts/make-icon-atlas.py --icons /path/to/lucide/svg

The icons are fetched from https://github.com/lucide-icons/lucide.
"""
import argparse
import sys
from pathlib import Path

try:
    import cairosvg
    from PIL import Image
except ImportError:  # pragma: no cover
    raise SystemExit('make-icon-atlas.py: cairosvg and Pillow are needed to bake the icons')

SIZE = 24  # Lucide's own grid: a 2 pixel stroke on 24 pixels
SUPERSAMPLE = 96
# name in the generated header -> lucide file
ICONS = (
    ('arrow_back', 'arrow-left'), ('arrow_forward', 'arrow-right'), ('arrow_up', 'arrow-up'),
    ('refresh', 'rotate-ccw'), ('eye', 'eye'), ('chevron_down', 'chevron-down'),
    ('chevron_right', 'chevron-right'), ('settings', 'settings'), ('list', 'list'),
    ('grid', 'grid-2x2'), ('folder', 'folder'), ('home', 'house'), ('drive', 'hard-drive'),
    ('box', 'box'), ('glasses', 'glasses'), ('compass', 'compass'), ('sliders', 'sliders-horizontal'), ('video', 'file-play'), ('play', 'play'), ('image', 'image'), ('file', 'file'), ('close', 'x'),
)


def bake(svg):
    """Rasterise the stroke icon to a square grey bitmap; white ink on black."""
    # Lucide draws with stroke="currentColor", which rasterises black by default, so the ink
    # colour is substituted before rasterising: these are coverage masks, not coloured art.
    source = svg.read_text(encoding='utf-8').replace('currentColor', '#ffffff')
    png = cairosvg.svg2png(bytestring=source.encode('utf-8'), output_width=SUPERSAMPLE, output_height=SUPERSAMPLE)
    from io import BytesIO
    image = Image.open(BytesIO(png)).convert('L').resize((SIZE, SIZE), Image.LANCZOS)
    return bytes(image.tobytes())


def main():
    parser = argparse.ArgumentParser(description='Bake the Lucide icon set')
    parser.add_argument('--icons', type=Path, required=True, help='directory of lucide svg files')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'cpp/ui/assets')
    options = parser.parse_args()
    entries = []
    for name, source in ICONS:
        svg = options.icons / (source + '.svg')
        if not svg.is_file():
            raise SystemExit('make-icon-atlas.py: missing %s' % svg)
        entries.append((name, bake(svg)))
    lines = ['#pragma once', '#include <array>', '#include <cstdint>', '',
             '// Generated by scripts/make-icon-atlas.py from Lucide (ISC licence, see',
             '// licenses/Lucide-ISC.txt). Do not edit by hand.', '',
             'namespace lumaframevr::ui::assets {', '',
             'struct Icon { const char* name; const std::uint8_t* coverage; int width, height; };', '']
    for name, pixels in entries:
        lines.append('inline constexpr std::array<std::uint8_t, %d> icon_%s{{' % (len(pixels), name))
        assert len(pixels) == SIZE * SIZE, '%s baked %d pixels, expected %d' % (name, len(pixels), SIZE * SIZE)
        for start in range(0, len(pixels), SIZE):
            lines.append('    ' + ','.join(str(v) for v in pixels[start:start + SIZE]) + ',')
        lines.append('}};')
        lines.append('')
    lines.append('inline constexpr std::array<Icon, %d> icons{{' % len(entries))
    for name, _ in entries:
        lines.append('    {"%s", icon_%s.data(), %d, %d},' % (name, name, SIZE, SIZE))
    lines.append('}};')
    lines.append('}')
    lines.append('')
    (options.output / 'icons.hpp').write_text('\n'.join(lines), encoding='utf-8')
    print('baked %d icons into %s/icons.hpp' % (len(entries), options.output))
    return 0


if __name__ == '__main__':
    sys.exit(main())
